import assert from 'node:assert/strict'
import { register } from 'node:module'
import { test } from 'node:test'
register(new URL('./support/hooks.mjs', import.meta.url).href)
const { Gateway } = await import('../src/gateway.js')
const { Config } = await import('../src/index.js')

test('real MCP SDK serves tools/list and tools/call with authentication', { skip: !process.env.DSH_TEST_PROTOCOL_ROOT }, async () => {
  let executions = 0
  const ctx = { agents: { withInitiator: (_, fn) => fn() }, tools: { execute: async () => { executions++; return { results: [{ result: { content: [{ type: 'text', text: 'DSH MCP OK' }] } }], additionalContexts: [] } } }, sessions: { flush: async () => true } }
  const g = new Gateway(ctx, [{ name: 'mcp__existing__query', description: 'Existing MCP', parameters: { type: 'object', properties: {} } }], new Set())
  const mcp = await g.listen()
  g.begin({ agent: { session: {} }, signal: new AbortController().signal, recordToolCall() {}, turn: 0, step: 0 })
  const headers = { 'Content-Type': 'application/json', Accept: 'application/json, text/event-stream', Authorization: mcp.headers[0].value }
  const rpc = async (id, method, params = {}) => {
    const res = await fetch(mcp.url, { method: 'POST', headers, body: JSON.stringify({ jsonrpc: '2.0', id, method, params }) })
    assert.equal(res.status, 200, await res.clone().text())
    return res.json()
  }
  try {
    assert.equal((await fetch(mcp.url, { method: 'POST' })).status, 403)
    const init = await rpc(1, 'initialize', { protocolVersion: '2025-03-26', capabilities: {}, clientInfo: { name: 'test', version: '1' } })
    assert.ok(init.result.capabilities.tools)
    assert.equal((await rpc(2, 'tools/list')).result.tools[0].name, 'mcp__existing__query')
    assert.equal((await rpc(3, 'tools/call', { name: 'mcp__existing__query', arguments: {} })).result.content[0].text, 'DSH MCP OK')
    assert.equal(executions, 1)
  } finally { await g.close() }
})
test('real host schema exposes live plugin choices for autogenerated settings', { skip: !process.env.DSH_TEST_SCHEMA_ROOT }, () => {
  const fields = Config.dict
  for (const key of ['toolSource', 'toolApproval', 'nativeApproval', 'permissionMode', 'tools']) assert.equal(fields[key].meta.volatile, true, key)
})
